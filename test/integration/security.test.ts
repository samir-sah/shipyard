import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { join, resolve, sep } from 'node:path';
import { tmpdir } from 'node:os';
import { ListObjectsV2Command } from '@aws-sdk/client-s3';
import { createApp } from '../../src/api.js';
import { config } from '../../src/config.js';
import { pool, migrate, createDeployment, claimDeployment, recordDeploymentCommit, activateDeployment, claimArtifactDeletions } from '../../src/db.js';
import { s3, ensureBucket, uploadArtifacts, deleteDeploymentArtifacts } from '../../src/storage.js';
import { cleanupRetainedArtifacts } from '../../src/cleanup.js';
import { isolateDatabase } from '../isolated-db.js';
import { configureTestAuth, operatorToken, otherToken, operatorId, otherUserId } from '../auth-fixture.js';
import type { Deployment, Project } from '../../src/contracts.js';
import { httpFetch as fetch } from '../http.js';

test('owners, site hosts and retention stay isolated through public HTTP and S3', { skip: process.env.RUN_INTEGRATION !== '1', timeout: 60_000 }, async () => {
  const restoreDb = await isolateDatabase();
  const restoreAuth = configureTestAuth();
  const oldKey = config.webhookKey;
  const oldDays = config.retentionDays;
  const oldKeep = config.retentionKeep;
  config.webhookKey = 'test-only-webhook-key-not-used-in-production';
  const { queue } = await import('../../src/queue.js');
  const directory = await mkdtemp(join(tmpdir(), 'shipyard-security-'));
  const deployments: string[] = [];
  const server = createApp().listen(0, '127.0.0.1');
  await once(server, 'listening');
  const address = server.address();
  assert.ok(address && typeof address !== 'string');
  const base = `http://127.0.0.1:${address.port}`;
  const request = (path: string, token: string | null = operatorToken, body?: unknown, host?: string) => fetch(`${base}${path}`, { method: body === undefined ? 'GET' : 'POST', headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(body === undefined ? {} : { 'Content-Type': 'application/json' }), ...(host ? { Host: host } : {}) }, body: body === undefined ? undefined : JSON.stringify(body), redirect: 'manual' });
  async function complete(deployment: Deployment, label: string) {
    const claim = await claimDeployment(deployment.id, 1);
    assert.ok(claim);
    const sha = 'a'.repeat(40);
    await recordDeploymentCommit(deployment.id, claim.token, sha);
    await writeFile(join(directory, 'index.html'), `<h1>${label}</h1>`);
    await writeFile(join(directory, 'assets', 'app.js'), `console.log(${JSON.stringify(label)})`);
    const manifest = await uploadArtifacts(deployment.id, directory, undefined, { token: claim.token, commitSha: sha });
    assert.equal(await activateDeployment(deployment.id, claim.token, sha, manifest), 'active');
  }
  try {
    await migrate();
    await ensureBucket();
    await mkdir(join(directory, 'assets'));
    assert.equal((await request('/api/projects', null)).status, 401);
    const response = await request('/api/projects', operatorToken, { name: 'Owner A', repoUrl: 'https://github.com/example/site.git' });
    assert.equal(response.status, 201);
    const initial = await response.json() as { project: Project; deployment: Deployment };
    const project = initial.project;
    deployments.push(initial.deployment.id);
    assert.equal(project.ownerId, operatorId);
    assert.ok(project.siteUrl?.includes(`${project.slug}.sites.localhost`));
    assert.equal(((await (await request('/api/projects', otherToken)).json()) as { projects: Project[] }).projects.length, 0);
    for (const [path, body] of [[`/api/projects/${project.id}/deployments`, {}], [`/api/projects/${project.id}/rollback`, { deploymentId: initial.deployment.id }], [`/api/projects/${project.id}/webhook`, { enabled: true }], [`/api/projects/${project.id}/deployments/${initial.deployment.id}/retain`, { retained: true }]] as const) assert.equal((await request(path, otherToken, body)).status, 404);
    assert.equal((await request(`/api/projects/${project.id}/deployments`, otherToken)).status, 404);
    assert.equal((await request(`/api/deployments/${initial.deployment.id}/logs`, otherToken)).status, 404);
    const otherResponse = await request('/api/projects', otherToken, { name: 'Owner B', repoUrl: 'https://github.com/example/other.git' });
    const other = await otherResponse.json() as { project: Project; deployment: Deployment };
    deployments.push(other.deployment.id);
    assert.equal(other.project.ownerId, otherUserId);
    await complete(initial.deployment, 'First version');
    const host = `${project.slug}.sites.localhost:${address.port}`;
    const root = await request('/', null, undefined, host);
    assert.equal(root.status, 302);
    assert.equal(root.headers.get('location'), `/_shipyard/v/${initial.deployment.id}/`);
    const page = await request(root.headers.get('location')!, null, undefined, host);
    assert.equal(page.status, 200);
    assert.ok(!page.headers.get('content-security-policy')?.includes('sandbox'));
    assert.match(await page.text(), /First version/);
    const fallback = await request(`/versions/${project.slug}/${initial.deployment.id}/`, null);
    assert.match(fallback.headers.get('content-security-policy') ?? '', /sandbox/);
    assert.equal((await request('/api/projects', operatorToken, undefined, host)).status, 404);
    assert.equal((await request('/api/session', operatorToken, { token: operatorToken }, host)).status, 405);
    assert.equal((await request('/api/projects', operatorToken, undefined, 'attacker.example')).status, 404);
    assert.equal((await request(`/_shipyard/v/${initial.deployment.id}/`, null, undefined, `${other.project.slug}.sites.localhost:${address.port}`)).status, 404);
    const kept = await createDeployment(project.id); assert.ok(kept); deployments.push(kept.id); await complete(kept, 'Kept');
    const expired = await createDeployment(project.id); assert.ok(expired); deployments.push(expired.id); await complete(expired, 'Expired');
    const newest = await createDeployment(project.id); assert.ok(newest); deployments.push(newest.id); await complete(newest, 'Newest');
    assert.equal((await request(`/api/projects/${project.id}/deployments/${kept.id}/retain`, operatorToken, { retained: true })).status, 200);
    assert.equal((await request(`/api/projects/${project.id}/rollback`, operatorToken, { deploymentId: initial.deployment.id })).status, 200);
    for (const [index, id] of [initial.deployment.id, kept.id, expired.id, newest.id].entries()) await pool.query("UPDATE deployments SET finished_at=clock_timestamp()-interval '3 days'+$2*interval '1 minute' WHERE id=$1", [id, index]);
    config.retentionDays = 1;
    config.retentionKeep = 1;
    assert.deepEqual(await claimArtifactDeletions(), [{ deploymentId: expired.id }]);
    assert.equal((await request(`/versions/${project.slug}/${expired.id}/`, null)).status, 410);
    assert.equal((await request(`/api/projects/${project.id}/rollback`, operatorToken, { deploymentId: expired.id })).status, 404);
    config.retentionDays = 0;
    await cleanupRetainedArtifacts();
    assert.equal((await pool.query('SELECT artifact_state FROM deployments WHERE id=$1', [expired.id])).rows[0].artifact_state, 'deleted');
    assert.equal((await s3.send(new ListObjectsV2Command({ Bucket: config.s3Bucket, Prefix: `deployments/${expired.id}/` }))).Contents?.length ?? 0, 0);
    for (const id of [initial.deployment.id, kept.id, newest.id]) assert.equal((await request(`/versions/${project.slug}/${id}/`, null)).status, 200);
  } finally {
    config.webhookKey = oldKey;
    config.retentionDays = oldDays;
    config.retentionKeep = oldKeep;
    restoreAuth();
    server.closeAllConnections();
    await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
    for (const id of deployments) { await deleteDeploymentArtifacts(id); await queue.remove(`${id}-1`); }
    await queue.close();
    assert.ok(resolve(directory).startsWith(resolve(tmpdir()) + sep));
    await rm(directory, { recursive: true, force: true });
    await restoreDb();
    s3.destroy();
  }
});
